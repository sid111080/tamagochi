/// Справочный раздел с терминами (ТЗ §8.11: «короткий справочник с терминами»).
///
/// Учебный контент вынесен в отдельный слой (`data/content`) и отделён от
/// интерфейсного кода (ТЗ §4): новые термины добавляются новой строкой в
/// список, не трогая экран. Формулировки — короткие и простые, под возраст
/// 7–11 лет; сложный термин всегда объясняется простыми словами.
class GlossaryTerm {
  const GlossaryTerm({
    required this.emoji,
    required this.term,
    required this.definition,
  });

  /// Иконка-подсказка (не единственный способ понять, о чём термин).
  final String emoji;

  /// Название термина простыми словами.
  final String term;

  /// Короткое определение (1–2 предложения, без сложного жаргона).
  final String definition;
}

